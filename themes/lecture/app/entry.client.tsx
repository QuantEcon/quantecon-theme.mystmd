import { HydratedRouter } from 'react-router/dom';
import { startTransition, StrictMode } from 'react';
import { hydrateRoot } from 'react-dom/client';

// Hydration waits for an idle moment rather than starting as soon as the
// entry module runs, as React Router's default entry does. The FOUC guard
// (tests/visual/fouc.spec.ts) samples the server-rendered page at
// DOMContentLoaded and relies on hydration landing after that sample.
function hydrate() {
  startTransition(() => {
    hydrateRoot(
      document,
      <StrictMode>
        <HydratedRouter />
      </StrictMode>,
    );
  });
}

if (window.requestIdleCallback) {
  window.requestIdleCallback(hydrate);
} else {
  // Safari doesn't support requestIdleCallback
  // https://caniuse.com/requestidlecallback
  window.setTimeout(hydrate, 1);
}
